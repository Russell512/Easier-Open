import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import ts from 'typescript'

const source = await fs.readFile(new URL('../src/lib/workspaceTabs.ts', import.meta.url), 'utf8')
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const { workspacePage, routePage, pageHash, openPage, closePage, restoreWorkspace, reconcileWorkspace, splitPage, openNoteBeside, resizePanes, initialWorkspace } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)

const dashboard = workspacePage('dashboard')
const docs = workspacePage('documents')
const schoolA = workspacePage('dashboard', '測試學校 A|||MS Computer Science')
const schoolB = workspacePage('programs', '測試學校 A|||MEng Computer Science')
const initial = initialWorkspace()
let state = openPage(initial, schoolA)
state = openPage(state, docs)
state = openPage(state, schoolB)
assert.deepEqual(state.pages.map((page) => page.id), [dashboard.id, schoolA.id, docs.id, schoolB.id], 'opening appends tabs in order')
state = openPage(state, workspacePage('compare', schoolA.school))
assert.equal(state.pages.length, 4, 'opening a school from another feature reuses its tab')
assert.equal(state.activeId, schoolA.id)
assert.equal(openPage(state, schoolA), state, 'reselecting the active tab is a no-op')
assert.equal(initial.pages.length, 1, 'transitions do not mutate earlier state')
assert.equal(schoolA.tab, 'programs', 'school tabs use a consistent route')
assert.deepEqual(routePage(pageHash(schoolA)), schoolA, 'Chinese names and delimiters round-trip in URLs')
assert.equal(routePage('#view=unknown').id, dashboard.id)

assert.equal(closePage(state, schoolB.id).activeId, schoolA.id, 'closing inactive tab does not navigate')
assert.equal(closePage(state, schoolA.id).activeId, docs.id, 'closing active tab selects its right neighbor')
assert.equal(closePage(openPage(state, schoolB), schoolB.id).activeId, docs.id, 'last tab selects its left neighbor')
assert.deepEqual(closePage({ pages: [docs], activeId: docs.id, panes: [{pageId: docs.id, size: 1}] }, docs.id), initial, 'closing final tab returns to the dashboard')
assert.equal(closePage(state, 'missing'), state)

assert.deepEqual(restoreWorkspace(JSON.stringify(state), ''), state, 'reload restores tab order and selection')
assert.equal(restoreWorkspace(JSON.stringify(state), pageHash(docs)).activeId, docs.id, 'explicit URL takes precedence over saved active tab')
assert.equal(restoreWorkspace(JSON.stringify(initial), pageHash(schoolA)).pages.length, 2, 'deep link appends its school')
assert.deepEqual(restoreWorkspace('invalid JSON', ''), initial)
assert.deepEqual(restoreWorkspace(JSON.stringify({ pages: [null, {}, { tab: 'bad', school: null }, { tab: 'documents', school: 123 }] }), ''), initial)
const repaired = restoreWorkspace(JSON.stringify({ pages: [schoolA, { ...schoolA, id: 'forged-id' }, docs], activeId: 'missing' }), '')
assert.deepEqual(repaired.pages, [schoolA, docs], 'restore validates and deduplicates saved identities')
assert.equal(repaired.activeId, schoolA.id)
assert.equal(reconcileWorkspace(state, new Set([schoolA.school, schoolB.school])), state)
const pruned = reconcileWorkspace(state, new Set([schoolB.school]))
assert.deepEqual(pruned.pages, [dashboard, docs, schoolB], 'workbook import prunes missing school tabs, retaining feature tabs')
assert.equal(pruned.activeId, docs.id)
assert.deepEqual(reconcileWorkspace({ pages: [schoolA, schoolB], activeId: schoolA.id, panes: [{pageId: schoolA.id, size: 1}] }, new Set()), initial)

// Opening all schools never imposes a hidden tab limit or duplicates identities.
let many = initial
for (let i = 0; i < 40; i++) many = openPage(many, workspacePage('programs', `school-${i}`))
assert.equal(many.pages.length, 41)
for (const page of [...many.pages]) many = closePage(many, page.id)
assert.deepEqual(many, initial)
console.log('PASS: tab order, school deduplication, independent programs, close/fallback behavior, persistence validation, deep links, URL encoding, workbook reconciliation, and unlimited tabs.')

let split = splitPage(initial, schoolA)
assert.equal(split.panes.length, 2)
split = openNoteBeside(split, 'note-one')
split = openNoteBeside(split, 'note-two')
assert.equal(split.panes.length, 4)
assert.equal(splitPage(split, docs), split, 'a fifth split cannot hide an existing pane')
const resized = resizePanes(split, 0, .3)
assert.ok(Math.abs(resized.panes.reduce((n,p)=>n+p.size,0)-1) < 1e-10)
assert.equal(resized.panes[2].size, split.panes[2].size, 'resizing affects only the adjacent pair')
const closed = closePage(resized, schoolA.id)
assert.equal(closed.panes.length, 3)
assert.ok(Math.abs(closed.panes[1].size / closed.panes[2].size - resized.panes[2].size / resized.panes[3].size) < 1e-10, 'closing redistributes proportionally')
const moved = splitPage(split, schoolA, 'note:note-two', 'right')
assert.equal(moved.panes.length, 4)
assert.equal(moved.panes[3].pageId, schoolA.id)
assert.equal(new Set(moved.panes.map(p=>p.pageId)).size, 4)
assert.deepEqual(restoreWorkspace(JSON.stringify(resized), ''), resized, 'pane order and widths survive reload')
assert.equal(openNoteBeside(split, 'note-one').panes.length, 4, 'opening a visible note focuses it')
const replacedNote = openNoteBeside(split, 'note-three')
assert.equal(replacedNote.panes.length, 4)
assert.ok(replacedNote.panes.some(p=>p.pageId==='note:note-one'), 'a different visible note remains intact')
assert.ok(replacedNote.pages.some(p=>p.id==='note:note-two'), 'replaced note remains available as a tab')
const cleared = reconcileWorkspace(split, new Set([schoolA.school]), new Set())
assert.ok(cleared.pages.every(p=>!p.noteId), 'deleted notes cannot restore stale panes')
assert.deepEqual(routePage(pageHash(workspacePage('notes', null, '筆記 id'))), workspacePage('notes', null, '筆記 id'))
const legacy = restoreWorkspace(JSON.stringify({pages:[dashboard,schoolA],activeId:schoolA.id}), '')
assert.deepEqual(legacy.panes,[{pageId:schoolA.id,size:1}], 'existing single-pane preferences migrate safely')
const damaged = restoreWorkspace(JSON.stringify({...split,panes:[{pageId:schoolA.id,size:-2},{pageId:schoolA.id,size:1},{pageId:schoolA.id,size:3},{pageId:'missing',size:1}]}), '')
assert.equal(new Set(damaged.panes.map(p=>p.pageId)).size,damaged.panes.length)
assert.ok(damaged.panes.every(p=>p.size>0))
console.log('PASS: four-pane limit, note identity, pane movement, proportional close, adjacent resize, legacy migration, and recovery.')
